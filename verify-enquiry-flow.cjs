function load(file) {
  file = path.resolve(root, file); if (!path.extname(file)) file += '.ts';
  if (modules.has(file)) return modules.get(file).exports;
  const mod = { exports: {} }; modules.set(file, mod);
  const localRequire = id => id === 'server-only' ? {} : id === 'nodemailer' ? { createTransport: () => ({ sendMail: async mail => { if (rejectMail) throw new Error('simulated transport failure'); sent.push(mail); return { accepted: [mail.to] }; } }) } : id === 'next/headers' ? { cookies: async () => ({ get: () => undefined }) } : id.startsWith('@/') ? load('src/' + id.slice(2)) : id.startsWith('.') ? load(path.resolve(path.dirname(file), id)) : require(id);
  const js = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: true, target: ts.ScriptTarget.ES2020 } }).outputText;
  new Function('require', 'module', 'exports', js)(localRequire, mod, mod.exports);
  return mod.exports;
}
