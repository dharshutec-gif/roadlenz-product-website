/* Run with node scripts/verify-agriculture.cjs. Read-only CMS migration checks. */
const fs = require('fs');
const ts = require('typescript');
const assert = require('assert/strict');
const mod = { exports: {} };
new Function('module', 'exports', 'require', ts.transpileModule(fs.readFileSync('src/lib/agriculture-content.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(mod, mod.exports, require);
const upgrade = mod.exports.upgradeAgricultureSolution;
const original = JSON.parse(fs.readFileSync('data/db.json')).solutions.find(s => s.slug === 'agriculture');
const fixture = structuredClone(original);
upgrade(fixture);
const once = JSON.stringify(fixture);
upgrade(fixture);
assert.equal(JSON.stringify(fixture), once);
assert.deepEqual(fixture.recommendedProducts, original.recommendedProducts);
assert.deepEqual(fixture.relatedProductSlugs, original.relatedProductSlugs);
assert.deepEqual(fixture.heroMedia, original.heroMedia);
assert.equal(fixture.vehicleImage, original.vehicleImage);
const empty = { ...structuredClone(original), agricultureContent: { challengeTitle: 'Custom', mediaFallback: '' }, journeyStages: [], painPoints: [], benefits: [], faqs: [], liveStatus: [], recommendedProducts: [] };
upgrade(empty);
for (const key of ['journeyStages', 'painPoints', 'benefits', 'faqs', 'liveStatus', 'recommendedProducts']) assert.deepEqual(empty[key], []);
assert.equal(empty.agricultureContent.challengeTitle, 'Custom');
assert.equal(empty.agricultureContent.mediaFallback, '');
const customStage = { ...structuredClone(original), journeyStages: [{ title: 'Custom task', description: 'Custom description', status: '', details: [], media: { type: 'image', src: '' }, nodeX: 42, nodeY: 39 }] };
upgrade(customStage);
assert.equal(customStage.journeyStages[0].description, 'Custom description');
assert.equal(customStage.journeyStages[0].nodeX, 42);
assert.deepEqual(customStage.journeyStages[0].details, []);
const other = { slug: 'taxi', name: 'Unchanged' };
upgrade(other);
assert.deepEqual(other, { slug: 'taxi', name: 'Unchanged' });
console.log('PASS Agriculture migration idempotence, custom/empty preservation, media, product assignments and isolation');
